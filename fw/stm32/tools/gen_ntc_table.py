#!/usr/bin/env python3
"""Generate src/ntc_table.h: divider ratio (0..65535) of the NTC circuit every 5 C.

NTC 100 k (B25/50 = 3950) to GND, 22 k to 3V3: ratio = R_ntc / (R_ntc + 22 k).
Run:  python3 tools/gen_ntc_table.py > src/ntc_table.h
"""
import math

R25, B, R_PULLUP = 100e3, 3950.0, 22e3
T_MIN, T_MAX, STEP = -30, 160, 5


def ratio(t_c):
    r = R25 * math.exp(B * (1 / (t_c + 273.15) - 1 / 298.15))
    return r / (r + R_PULLUP)


temps = list(range(T_MIN, T_MAX + 1, STEP))
print("/* Generated by tools/gen_ntc_table.py - do not edit.")
print(" * NTC 100 k B3950 to GND, 22 k pull-up: divider ratio x 65535 at each table temperature. */")
print("#ifndef NTC_TABLE_H")
print("#define NTC_TABLE_H")
print()
print("#define NTC_TABLE_T_MIN_MC  (%d)" % (T_MIN * 1000))
print("#define NTC_TABLE_STEP_MK   %d" % (STEP * 1000))
print("#define NTC_TABLE_LEN       %d" % len(temps))
print()
print("static const uint16_t ntc_table[NTC_TABLE_LEN] = {")
for i in range(0, len(temps), 8):
    row = temps[i:i + 8]
    print("    " + " ".join("%5d," % round(ratio(t) * 65535) for t in row) + "  /* %d C .. */" % row[0])
print("};")
print()
print("#endif /* NTC_TABLE_H */")
